import Foundation

/// Lines exchanged with the clipboard helper on an Android phone (add-android-clipboard-sync design D2).
/// One JSON object per line; clipboard text travels as base64 of UTF-8, so line breaks and quotes in
/// the text never break the framing.
public enum ClipboardProtocol {
    /// Must match `PROTOCOL_VERSION` in android/clipboard-helper (checked by a unit test).
    public static let version = 1
    /// Longest text either side sends, in UTF-8 bytes before base64 (spec «Что не передаётся»).
    public static let maxTextBytes = 1 << 20

    /// Messages from the helper.
    public enum Message: Equatable, Sendable {
        case hello(version: Int, sdk: Int, listening: Bool)
        case changed(String)
        case ack(Int)
        case pong
        case error(String)
    }

    public static func fits(_ text: String) -> Bool { text.utf8.count <= maxTextBytes }

    /// `{"t":"set","id":N,"b64":"…"}`; nil for text over the limit.
    public static func set(_ text: String, id: Int) -> String? {
        guard fits(text) else { return nil }
        return #"{"t":"set","id":\#(id),"b64":"\#(Data(text.utf8).base64EncodedString())"}"# + "\n"
    }

    public static let ping = #"{"t":"ping"}"# + "\n"

    /// Parses one line from the helper; nil for anything malformed or unknown.
    public static func parse(_ line: Substring) -> Message? {
        guard let object = try? JSONSerialization.jsonObject(with: Data(line.utf8)) as? [String: Any],
              let type = object["t"] as? String else { return nil }
        switch type {
        case "hello":
            guard let version = object["v"] as? Int else { return nil }
            return .hello(version: version, sdk: object["sdk"] as? Int ?? 0,
                          listening: object["watch"] as? String == "listener")
        case "changed":
            guard let encoded = object["b64"] as? String, let data = Data(base64Encoded: encoded),
                  data.count <= maxTextBytes, let text = String(data: data, encoding: .utf8) else { return nil }
            return .changed(text)
        case "ack":
            return (object["id"] as? Int).map(Message.ack)
        case "pong":
            return .pong
        case "error":
            return .error(object["msg"] as? String ?? "")
        default:
            return nil
        }
    }

    public static func parse(_ line: String) -> Message? { parse(Substring(line)) }
}

/// Which clipboard text goes where (design D5). Pure state, no pasteboard or adb: the app feeds it
/// pasteboard changes, phone changes and connections and acts on what it returns.
public struct ClipboardRelay: Sendable {
    /// Pasteboard types that mark content programs do not want shared (nspasteboard.org).
    public static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
    ]

    /// Last text sent to each phone, or received from it.
    private var known: [UInt16: String] = [:]
    /// `changeCount` of the Mac pasteboard right after this app wrote phone text to it.
    private var ownWrite: Int?

    public init() {}

    /// The text of a Mac pasteboard state that may leave the Mac, or nil (private, no text, too long).
    public static func shareable(types: Set<String>, text: String?) -> String? {
        guard types.isDisjoint(with: privateTypes), let text, !text.isEmpty, ClipboardProtocol.fits(text) else { return nil }
        return text
    }

    /// The Mac pasteboard changed. Returns the phones to send the text to.
    public mutating func macChanged(changeCount: Int, types: Set<String>, text: String?,
                                    connected peers: [UInt16]) -> [(peer: UInt16, text: String)] {
        if changeCount == ownWrite { return [] }
        guard let text = Self.shareable(types: types, text: text) else { return [] }
        var sends: [(peer: UInt16, text: String)] = []
        for peer in peers where known[peer] != text {
            known[peer] = text
            sends.append((peer, text))
        }
        return sends
    }

    /// A phone's helper is up; `macText` is `shareable(…)` of the current pasteboard.
    /// Returns the text to send, if the phone has not seen it.
    public mutating func connected(_ peer: UInt16, macText: String?) -> String? {
        guard let macText, known[peer] != macText else { return nil }
        known[peer] = macText
        return macText
    }

    /// A phone reported new clipboard text. Returns the text to put on the Mac pasteboard, or nil for
    /// an echo of what was just sent there. The text then counts as known to every phone, so it is not
    /// relayed to the others (spec «Без эха и зацикливания»).
    public mutating func phoneChanged(_ peer: UInt16, text: String, allPeers: [UInt16]) -> String? {
        guard known[peer] != text, ClipboardProtocol.fits(text) else { return nil }
        for other in Set(allPeers + [peer]) { known[other] = text }
        return text
    }

    /// Call right after writing phone text to the Mac pasteboard, with its new `changeCount`.
    public mutating func wroteToMac(changeCount: Int) {
        ownWrite = changeCount
    }

    /// A phone is gone or switched off; it gets the current text again when it comes back.
    public mutating func forget(_ peer: UInt16) {
        known[peer] = nil
    }
}
