import Foundation

/// macOS virtual key codes (kVK_*, ANSI and ISO keyboards) → HID Usage IDs of the Keyboard/Keypad page
/// (design D10). The usage is the physical key: the host applies its own keyboard layout, as with any
/// USB or Bluetooth keyboard.
public enum KeyCodeMap {
    /// HID usage for a macOS virtual key code, or nil for keys without a mapping (Fn, media keys…).
    /// Modifier keys map to 0xE0…0xE7.
    public static func usage(forKeyCode keyCode: UInt16) -> UInt8? {
        table[keyCode]
    }

    /// True for modifier key codes (they arrive as flagsChanged events).
    public static func isModifier(_ keyCode: UInt16) -> Bool {
        guard let usage = table[keyCode] else { return false }
        return (0xE0...0xE7).contains(usage)
    }

    static let table: [UInt16: UInt8] = [
        // Letters
        0x00: 0x04, // A
        0x0B: 0x05, // B
        0x08: 0x06, // C
        0x02: 0x07, // D
        0x0E: 0x08, // E
        0x03: 0x09, // F
        0x05: 0x0A, // G
        0x04: 0x0B, // H
        0x22: 0x0C, // I
        0x26: 0x0D, // J
        0x28: 0x0E, // K
        0x25: 0x0F, // L
        0x2E: 0x10, // M
        0x2D: 0x11, // N
        0x1F: 0x12, // O
        0x23: 0x13, // P
        0x0C: 0x14, // Q
        0x0F: 0x15, // R
        0x01: 0x16, // S
        0x11: 0x17, // T
        0x20: 0x18, // U
        0x09: 0x19, // V
        0x0D: 0x1A, // W
        0x07: 0x1B, // X
        0x10: 0x1C, // Y
        0x06: 0x1D, // Z
        // Digits row
        0x12: 0x1E, // 1
        0x13: 0x1F, // 2
        0x14: 0x20, // 3
        0x15: 0x21, // 4
        0x17: 0x22, // 5
        0x16: 0x23, // 6
        0x1A: 0x24, // 7
        0x1C: 0x25, // 8
        0x19: 0x26, // 9
        0x1D: 0x27, // 0
        // Editing and whitespace
        0x24: 0x28, // Return
        0x35: 0x29, // Escape
        0x33: 0x2A, // Delete (Backspace)
        0x30: 0x2B, // Tab
        0x31: 0x2C, // Space
        0x1B: 0x2D, // - _
        0x18: 0x2E, // = +
        0x21: 0x2F, // [ {
        0x1E: 0x30, // ] }
        0x2A: 0x31, // \ |
        0x29: 0x33, // ; :
        0x27: 0x34, // ' "
        0x32: 0x35, // ` ~
        0x2B: 0x36, // , <
        0x2F: 0x37, // . >
        0x2C: 0x38, // / ?
        0x39: 0x39, // Caps Lock (a normal key in HID)
        0x0A: 0x64, // ISO § ± (Non-US \ |)
        // Function keys
        0x7A: 0x3A, // F1
        0x78: 0x3B, // F2
        0x63: 0x3C, // F3
        0x76: 0x3D, // F4
        0x60: 0x3E, // F5
        0x61: 0x3F, // F6
        0x62: 0x40, // F7
        0x64: 0x41, // F8
        0x65: 0x42, // F9
        0x6D: 0x43, // F10
        0x67: 0x44, // F11
        0x6F: 0x45, // F12
        0x69: 0x68, // F13
        0x6B: 0x69, // F14
        0x71: 0x6A, // F15
        // Navigation
        0x72: 0x49, // Help / Insert
        0x73: 0x4A, // Home
        0x74: 0x4B, // Page Up
        0x75: 0x4C, // Forward Delete
        0x77: 0x4D, // End
        0x79: 0x4E, // Page Down
        0x7C: 0x4F, // Right Arrow
        0x7B: 0x50, // Left Arrow
        0x7D: 0x51, // Down Arrow
        0x7E: 0x52, // Up Arrow
        // Keypad
        0x47: 0x53, // Clear (Num Lock)
        0x4B: 0x54, // Keypad /
        0x43: 0x55, // Keypad *
        0x4E: 0x56, // Keypad -
        0x45: 0x57, // Keypad +
        0x4C: 0x58, // Keypad Enter
        0x53: 0x59, // Keypad 1
        0x54: 0x5A, // Keypad 2
        0x55: 0x5B, // Keypad 3
        0x56: 0x5C, // Keypad 4
        0x57: 0x5D, // Keypad 5
        0x58: 0x5E, // Keypad 6
        0x59: 0x5F, // Keypad 7
        0x5B: 0x60, // Keypad 8
        0x5C: 0x61, // Keypad 9
        0x52: 0x62, // Keypad 0
        0x41: 0x63, // Keypad .
        0x51: 0x67, // Keypad =
        // Modifiers (left / right)
        0x3B: 0xE0, // Left Control
        0x38: 0xE1, // Left Shift
        0x3A: 0xE2, // Left Option (Alt)
        0x37: 0xE3, // Left Command (GUI)
        0x3E: 0xE4, // Right Control
        0x3C: 0xE5, // Right Shift
        0x3D: 0xE6, // Right Option
        0x36: 0xE7, // Right Command
    ]
}
